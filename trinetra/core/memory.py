"""Regression memory + git hook install. The 'wall' that makes Trinetra unskippable."""
import json
import os

TRINETRA_DIR = ".trinetra"


def tri_path(repo, *parts):
    return os.path.join(repo, TRINETRA_DIR, *parts)


def load_config(repo):
    p = tri_path(repo, "config.json")
    if os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    return {}


def save_config(repo, cfg):
    os.makedirs(tri_path(repo), exist_ok=True)
    with open(tri_path(repo, "config.json"), "w") as f:
        json.dump(cfg, f, indent=2)


def install_hook(repo, python_exe, pythonpath=None):
    hooks = os.path.join(repo, ".git", "hooks")
    if not os.path.isdir(hooks):
        raise RuntimeError("not a git repository (no .git/hooks)")
    pp_line = f'export PYTHONPATH="{pythonpath}"\n' if pythonpath else ""
    content = (
        "#!/bin/sh\n"
        "# Trinetra pre-commit wall — blocks commits that (re)introduce High/Critical vulns\n"
        f"{pp_line}"
        f'exec "{python_exe}" -m trinetra.cli guard --repo "$(git rev-parse --show-toplevel)"\n'
    )
    hp = os.path.join(hooks, "pre-commit")
    with open(hp, "w") as f:
        f.write(content)
    os.chmod(hp, 0o755)
    return hp


REG_TEMPLATE = '''# AUTO-GENERATED by `trinetra freeze` — do not edit.
# Every frozen vulnerability must stay absent. A failing test = a bug came back.
import pytest
from trinetra.core.astra import Context
from trinetra.core.loader import load_astras

FROZEN = {frozen!r}
SOURCE = {source!r}
_ASTRAS = {{a.ID: a for a in load_astras()}}


@pytest.mark.parametrize("aid", FROZEN)
def test_vuln_stays_fixed(aid):
    a = _ASTRAS[aid]
    proven, evidence = a.run(Context(source_root=SOURCE))
    assert not proven, f"REGRESSION: {{a.NAME}} came back -> {{evidence}}"
'''


def write_regression_tests(repo, frozen_ids, source):
    regdir = tri_path(repo, "regression")
    os.makedirs(regdir, exist_ok=True)
    path = os.path.join(regdir, "test_frozen_state.py")
    with open(path, "w") as f:
        f.write(REG_TEMPLATE.format(frozen=frozen_ids, source=source))
    with open(tri_path(repo, "regression.json"), "w") as f:
        json.dump({"frozen": frozen_ids, "source": source}, f, indent=2)
    return path
